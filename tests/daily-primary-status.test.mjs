import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const app=readFileSync(new URL('../app.js',import.meta.url),'utf8');
const fn=app.match(/function dailyResultStatus\([^]*?\n}/)[0];
const status=new Function('LIVE_STATUS',`${fn};return dailyResultStatus;`)({queued:{label:'เข้าคิว'},completed:{label:'เสร็จ'}});
const primary={id:'v1',recheck_id:'q1',source_stamp:{file_count:8}};
const row={job_status:'queued',autoPaused:true,latestRecheck:{id:'q1',status:'confirmed'}};
const before=JSON.stringify(row);
assert.equal(status(row,{primaryResult:primary}).label,'ใช้ผลรันมือเป็นผลหลักแล้ว');
assert.equal(status(row,{primaryResult:primary}).manual,null);
assert.equal(status(row,{primaryResult:primary}).automatic,'รอบอัตโนมัติ: พักรัน');
assert.match(status({...row,latestRecheck:{id:'q2',status:'ready'}},{primaryResult:primary}).manual,/รอหัวหน้า/);
assert.match(status(row).manual,/ยังไม่ใช้เป็นผลหลัก/);
assert.equal(status(row).primary,undefined);
assert.equal(JSON.stringify(row),before);
assert.match(app,/fileCount: primary \? \(Array.isArray\(primary.source_stamp\)\?primary.source_stamp.length/);
assert.match(app,/parsedCount: primary \? \(Array.isArray\(primary.source_stamp\)\?primary.source_stamp.length/);
const sb=readFileSync(new URL('../supabase.js',import.meta.url),'utf8');
assert.match(sb,/resolved_count:v.case_set.closed_count/);
assert.match(sb,/primaryResult:v\|\|null/);
console.log('PASS daily summary separates accepted primary, staged manual and held automatic work without data mutation');
