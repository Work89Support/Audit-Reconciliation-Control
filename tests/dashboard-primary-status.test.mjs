import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const app=readFileSync(new URL('../app.js',import.meta.url),'utf8');
const missing=new Function(`${app.match(/function cloudMissingGroupsText\([^]*?\n}/)[0]};return cloudMissingGroupsText;`)();
const structured=[{kind:'STM',label:'SCB A',direction:'deposit'},{kind:'PM',source_labels:['CYBERPLUS'],direction:'withdraw'}];
const snapshot=JSON.stringify(structured);
assert.equal(missing(structured),'STM · SCB A · ฝาก, PM · CYBERPLUS · ถอน');
assert.equal(JSON.stringify(structured),snapshot);
const status=new Function('LIVE_STATUS',`${app.match(/function dailyResultStatus\([^]*?\n}/)[0]};return dailyResultStatus;`)({queued:{label:'เข้าคิว'}});
const lifecycle={autoPaused:true,job_status:'queued',latestRecheck:{id:'manual',status:'confirmed'}};
assert.match(status(lifecycle).manual,/ยังไม่ใช้เป็นผลหลัก/);
const accepted=status(lifecycle,{primaryResult:{recheck_id:'manual'}});
assert.equal(accepted.label,'ใช้ผลรันมือเป็นผลหลักแล้ว');
assert.equal(accepted.automatic,'รอบอัตโนมัติ: พักรัน');
assert.equal(accepted.manual,null);
assert.match(app,/const missingText = \(row\) => cloudMissingGroupsText\(row.missing_groups\)/);
assert.match(app,/dailyResultStatus\(checklistRow\|\|\{\},row\)/);
assert.match(app,/เคสรวมชุดปัจจุบัน/);
assert.match(app,/ค้าง \$\{num\(lifecycle.open_count\)\} · ปิดแล้ว \$\{num\(lifecycle.resolved_count\)\}/);
assert.match(app,/ผลหลัก \$\{checklistRow\?\.primaryFileCount==null/);
assert.match(app,/h\(missingText\(row\)\)/);
assert.match(app,/if \(row.primaryResult \|\| row.status === "completed"\) item.completed\+\+/);
console.log('PASS Dashboard: structured missing files, shared primary/manual/automatic status, received vs accepted files and open/closed case labels; input unchanged');
